import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const sources = {
  iso: 'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml',
  cldr: 'https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-core/supplemental/currencyData.json',
};
const raw = {};
await mkdir(new URL('.cache/currency-data/',root),{recursive:true});
for (const [key,url] of Object.entries(sources)) {
  const cache = new URL(`.cache/currency-data/${key}.${key==='iso'?'xml':'json'}`,root);
  if (process.argv.includes('--cached')) raw[key] = await readFile(cache,'utf8');
  else { const response = await fetch(url,{signal:AbortSignal.timeout(20000)}); if(!response.ok) throw Error(`${key}: ${response.status}`); raw[key] = await response.text(); await writeFile(cache,raw[key]); }
}
const cldr=JSON.parse(raw.cldr).supplemental;
const decode = text=>text.replace(/&amp;/g,'&').replace(/&apos;/g,"'").replace(/&quot;/g,'"').replace(/&#(\d+);/g,(_,n)=>String.fromCodePoint(Number(n)));
const currencies={};
for(const entry of raw.iso.match(/<CcyNtry>[\s\S]*?<\/CcyNtry>/g)??[]) {
  const code=entry.match(/<Ccy>([A-Z]{3})<\/Ccy>/)?.[1], digits=entry.match(/<CcyMnrUnts>(\d)<\/CcyMnrUnts>/)?.[1];
  // Funds, metals, testing codes and 'no currency' are not destination money.
  if(!code || digits===undefined || /IsFund="true"/.test(entry)) continue;
  const name=decode(entry.match(/<CcyNm[^>]*>(.*?)<\/CcyNm>/)[1]);
  currencies[code]={name,digits:Number(digits)};
}
if(Object.keys(currencies).length<150 || !currencies.COP || currencies.KWD.digits!==3) throw Error('Currency source validation failed.');
const regions=Object.fromEntries(Object.entries(cldr.currencyData.region).map(([region,entries])=>[region,entries.flatMap(entry=>Object.entries(entry).filter(([code,value])=>currencies[code]&&value._tender!=='false').map(([code,value])=>({code,from:value._from??'',to:value._to??''}))) ]));
const metadata={isoPublished:raw.iso.match(/Pblshd="([^"]+)"/)[1],cldrVersion:cldr.version._cldrVersion,retrievedAt:new Date().toISOString(),sources,sha256:Object.fromEntries(Object.entries(raw).map(([key,value])=>[key,createHash('sha256').update(value).digest('hex')]))};
await writeFile(new URL('src/lib/currency-data.ts',root),`// Generated by scripts/update-currency-data.mjs from ISO 4217 (SIX) and Unicode CLDR.\nexport const CURRENCY_DATA_SOURCE = ${JSON.stringify(metadata,null,2)} as const;\nexport const CURRENCY_DEFINITIONS = ${JSON.stringify(Object.fromEntries(Object.entries(currencies).sort()),null,2)} as const;\nexport const CURRENCY_CODES = ${JSON.stringify(Object.keys(currencies).sort())} as const;\nexport const TERRITORY_CURRENCY_PERIODS = ${JSON.stringify(regions,null,2)} as const;\n`);
console.log(`Generated ${Object.keys(currencies).length} currencies and ${Object.keys(regions).length} territory mappings. ISO ${metadata.isoPublished}, CLDR ${metadata.cldrVersion}.`);
const contractPath = new URL('openapi/travelmate-api.json',root);
const contract = JSON.parse(await readFile(contractPath,'utf8'));
const prior = JSON.stringify(contract.components.schemas.CurrencyCode.enum);
function update(value) {
  if(!value || typeof value!=='object') return;
  if(Array.isArray(value.enum) && JSON.stringify(value.enum)===prior) value.enum=Object.keys(currencies).sort();
  Object.values(value).forEach(update);
}
update(contract);
await writeFile(contractPath,JSON.stringify(contract,null,2)+'\n');
